export function getLocalTime(city: City): string {
  if (!city.timezone) return ''
  return new Date().toLocaleTimeString('ja-JP', {
    timeZone: city.timezone,
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  })
}

export function getGoogleMapsEmbedUrl(city: City): string {
  return `https://maps.google.com/maps?q=${city.latitude},${city.longitude}&z=13&output=embed`
}

export function getGoogleMapsUrl(city: City): string {
  return `https://www.google.com/maps/@${city.latitude},${city.longitude},13z`
}
