/**
 * 一次細分区域コード(6桁)から [longitude, latitude] を返す
 * 対応する座標がない場合は null を返す
 */
export function getAreaCoords(areaCode: string): [number, number] | null {
  // 直接マッチ (officesレベルのコード)
  if (PREFECTURE_COORDS[areaCode]) {
    return PREFECTURE_COORDS[areaCode]
  }

  // class10s -> parent office コードを経由
  const parentCode = CLASS10_TO_PARENT[areaCode]
  if (parentCode && PREFECTURE_COORDS[parentCode]) {
    return PREFECTURE_COORDS[parentCode]
  }

  return null
}
